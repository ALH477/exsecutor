segment readable executable
  start:
	xor	rbx, rbx
  .case:
	cmp	rbx, CASE_COUNT
	jge	.all_done
	mov	r12, rbx
	imul	r12, CASE_STRIDE

	lea	rdi, [rec]
	mov	rsi, [ctab + r12 + 0]		; code_num
	mov	rdx, [ctab + r12 + 8]		; file_id
