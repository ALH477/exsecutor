; Byte-exact human-readable rendering, five diagnostics chosen for the parts
; of the format that are easy to get subtly wrong rather than the part that is
; easy to look at.
;
; Case A is the one that matters: the file PATH and the echoed source line
; both contain U+202E, and the span itself begins with it. It pins three
; separate things at once --
;   - the path is escaped (a file literally named with a bidi override
;     otherwise renders a header that lies about which file failed);
;   - the echoed line is escaped;
;   - the CARET RUN is measured in ESCAPED columns, not source bytes. The
;     span is 10 source bytes and 20 rendered ones, and the carets must be 20
;     wide and start under the `\` of `\u{202e}`. Computing that from raw
;     offsets is the obvious mistake and misaligns by six per escaped
;     codepoint.
; Case B has no source and no fix: header line only, nothing else emitted.
; Case C has a ZERO-LENGTH span -- an insertion point -- which must still get
;   exactly one caret rather than none.
; Case D carries a delete fix, whose replacement text is empty, so the
;   `-> "..."` clause must be omitted entirely rather than rendered empty.
; Case E has a span running PAST the end of its line; the echoed line and the
;   caret run must both stop at the line end.
;
; Every expected byte string is generated from an independent model of the
; documented format, not captured from this renderer's own output.
;
; Exit 0 = all cases matched; 11+K = case K (0-based) mismatched.
;
; TEST: run=yes expect-exit=0 audit=pass

include 'format/format.inc'

