	mov	r8,  [ctab + r12 + 24]		; span len
	call	diag_init

	mov	rax, [ctab + r12 + 40]		; source length
	test	rax, rax
	jz	.no_src
	lea	rdi, [rec]
	lea	rsi, [srcblob]
	add	rsi, [ctab + r12 + 32]
	mov	rdx, [ctab + r12 + 40]
	lea	rcx, [pathblob]
	add	rcx, [ctab + r12 + 48]
	mov	r8,  [ctab + r12 + 56]
	call	diag_attach_source
  .no_src:

	mov	rax, [ctab + r12 + 64]		; fix kind
	test	rax, rax
	jz	.no_fix
	cmp	rax, DIAG_FIX_REPLACE
	je	.f_replace
	cmp	rax, DIAG_FIX_INSERT
	je	.f_insert
	; delete
	lea	rdi, [rec]
	call	diag_fix_ptr
	mov	rdi, rax
	mov	rsi, [ctab + r12 + 8]
	mov	rdx, [ctab + r12 + 72]
	mov	rcx, [ctab + r12 + 80]
	call	diag_fix_delete
	jmp	.no_fix
  .f_replace:
	lea	rdi, [rec]
	call	diag_fix_ptr
	mov	rdi, rax
	mov	rsi, [ctab + r12 + 8]
	mov	rdx, [ctab + r12 + 72]
	mov	rcx, [ctab + r12 + 80]
	lea	r8, [textblob]
	add	r8, [ctab + r12 + 88]
	mov	r9, [ctab + r12 + 96]
	call	diag_fix_replace
	jmp	.no_fix
  .f_insert:
	lea	rdi, [rec]
	call	diag_fix_ptr
	mov	rdi, rax
	mov	rsi, [ctab + r12 + 8]
	mov	rdx, [ctab + r12 + 72]
	lea	rcx, [textblob]
	add	rcx, [ctab + r12 + 88]
	mov	r8, [ctab + r12 + 96]
	call	diag_fix_insert
  .no_fix:

	lea	rdi, [rec]
	lea	rsi, [outbuf]
	mov	rdx, 4096
	call	diag_render_text
	mov	r13, rax
	test	rdx, rdx
	jnz	.mismatch		; nothing here should ever truncate

	lea	rdi, [outbuf]
	mov	rsi, r13
	lea	rdx, [expblob]
	add	rdx, [ctab + r12 + 104]
	mov	rcx, [ctab + r12 + 112]
	call	diagt_eq
	test	eax, eax
	jz	.mismatch

	inc	rbx
	jmp	.case

  .all_done:
	mov	eax, 231
	xor	edi, edi
	syscall

	; exit 11 + case index, so a failure names WHICH case failed
  .mismatch:
	lea	rdi, [rbx + 11]
	mov	eax, 231
	syscall

; ---- byte helpers (fixture-local; see this file's header) ------------------
; diagt_eq(rdi=a, rsi=alen, rdx=b, rcx=blen) -> eax = 1 if identical.
  diagt_eq:
	cmp	rsi, rcx
	jne	.ne
	xor	r8, r8
  .l:
	cmp	r8, rsi
	jge	.eq
	mov	al, [rdi + r8]
	cmp	al, [rdx + r8]
	jne	.ne
	inc	r8
	jmp	.l
  .eq:
	mov	eax, 1
	ret
  .ne:
	xor	eax, eax
	ret

; diagt_find(rdi=hay, rsi=hlen, rdx=needle, rcx=nlen) -> eax = 1 if `needle`
; occurs anywhere in `hay`. This is what makes the "never the raw codepoint"
; check independent of the expected-output comparison: even if BOTH the
; renderer and this fixture's expected bytes were wrong in the same way, a
; raw bidi override in the output would still be caught here.
  diagt_find:
	test	rcx, rcx
	jz	.no
	cmp	rsi, rcx
	jb	.no
	mov	r8, rsi
	sub	r8, rcx			; last valid start offset
	xor	r9, r9
  .outer:
	cmp	r9, r8
	jg	.no
	xor	r10, r10
  .inner:
	cmp	r10, rcx
	jge	.yes
	mov	r11, r9
	add	r11, r10
	mov	al, [rdi + r11]
	cmp	al, [rdx + r10]
	jne	.next
	inc	r10
	jmp	.inner
  .next:
	inc	r9
	jmp	.outer
  .yes:
	mov	eax, 1
	ret
  .no:
	xor	eax, eax
	ret

