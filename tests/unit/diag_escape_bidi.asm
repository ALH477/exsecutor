	mov	rsi, [gott]
	lea	rdx, [sample]
	add	rdx, r12
	mov	rcx, r13
	call	diagt_find
	test	eax, eax
	jnz	.fail3
	mov	r12d, [nd_tab + rbx*8]
	mov	r13d, [nd_tab + rbx*8 + 4]
	lea	rdi, [outj]
	mov	rsi, [gotj]
	lea	rdx, [sample]
	add	rdx, r12
	mov	rcx, r13
	call	diagt_find
	test	eax, eax
	jnz	.fail3
	inc	rbx
	jmp	.scan
  .scan_done:

	; ---- check 4: the classifier's range edges ----
	xor	rbx, rbx
  .cls:
	cmp	rbx, CLS_COUNT
	jge	.cls_done
	mov	edi, [cls_tab + rbx*8]
	call	diag_is_dangerous_cp
	cmp	eax, [cls_tab + rbx*8 + 4]
	jne	.fail4
	inc	rbx
	jmp	.cls
  .cls_done:

	mov	eax, 231
	xor	edi, edi
	syscall

