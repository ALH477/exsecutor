	mov	eax, 231
	mov	edi, 11
	syscall
  .fail2:
	mov	eax, 231
	mov	edi, 12
	syscall
  .fail3:
	mov	eax, 231
	mov	edi, 13
	syscall
  .fail4:
	mov	eax, 231
	mov	edi, 14
	syscall

; ---- byte helpers (fixture-local; see this file's header) ------------------
; diagt_eq(rdi=a, rsi=alen, rdx=b, rcx=blen) -> eax = 1 if identical.
  diagt_eq:
	cmp	rsi, rcx
	jne	.ne
	xor	r8, r8
  .l:
	cmp	r8, rsi
	jge	.eq
	mov	al, [rdi + r8]
	cmp	al, [rdx + r8]
	jne	.ne
	inc	r8
	jmp	.l
  .eq:
	mov	eax, 1
	ret
  .ne:
	xor	eax, eax
	ret

; diagt_find(rdi=hay, rsi=hlen, rdx=needle, rcx=nlen) -> eax = 1 if `needle`
; occurs anywhere in `hay`. This is what makes the "never the raw codepoint"
; check independent of the expected-output comparison: even if BOTH the
; renderer and this fixture's expected bytes were wrong in the same way, a
; raw bidi override in the output would still be caught here.
  diagt_find:
	test	rcx, rcx
	jz	.no
	cmp	rsi, rcx
	jb	.no
	mov	r8, rsi
	sub	r8, rcx			; last valid start offset
	xor	r9, r9
  .outer:
	cmp	r9, r8
	jg	.no
	xor	r10, r10
  .inner:
	cmp	r10, rcx
	jge	.yes
	mov	r11, r9
	add	r11, r10
	mov	al, [rdi + r11]
	cmp	al, [rdx + r10]
	jne	.next
	inc	r10
	jmp	.inner
  .next:
	inc	r9
	jmp	.outer
  .yes:
	mov	eax, 1
	ret
  .no:
	xor	eax, eax
	ret

