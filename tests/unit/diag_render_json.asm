; Byte-exact machine-readable rendering. §8.3: "Stable machine-readable
; codes. Codes are permanent; text is not. Tools match codes, never English
; prose." The point of this fixture is that the structured output is a
; contract, so it is checked byte for byte rather than parsed loosely.
;
; The same five diagnostics as tests/unit/diag_render_text.asm, so the two
; modes are pinned against the same inputs:
;   A -- bidi in the path, in the echoed source, and inside the span itself,
;        with a `replace` fix. In JSON mode every escape's backslash doubles,
;        so `\u{202e}` is carried as `\\u{202e}`; a parser hands the consumer
;        back exactly the text-mode rendering, which is what keeps a tool that
;        prints `snippet` raw from printing a live bidi override.
;   B -- no source, no fix: `"fix":null`, and `fix` is PRESENT rather than
;        omitted, so a consumer's schema does not change shape.
;   C -- an `insert` fix (zero-length edit span, non-empty text).
;   D -- a `delete` fix (non-empty edit span, empty text -> `"text":""`).
;   E -- no fix, with a span extending past its line; `snippet` is the span's
;        own bytes and is NOT clamped to the line (the human mode clamps
;        because a caret run must fit on one line; the machine mode does not,
;        because a consumer asked for the span).
;
; The expected records are generated by an independent model of the format
; and each one is run through a real JSON parser at generation time, so
; byte-equality here is also evidence of well-formedness -- see the generator
; note in this repo's diag/ report.
;
; Exit 0 = all cases matched; 11+K = case K (0-based) mismatched.
;
; TEST: run=yes expect-exit=0 audit=pass

